function f = fun1(xx)
    a=[1.25  8.75  0.5  5.75  3  7.25];  % 工地的横坐标
    b=[1.25  0.75  4.75	5  6.5  7.25];   % 工地的纵坐标
    x = [xx(13) xx(15)];
    y = [xx(14) xx(16)];
    c = [];
    for j = 1:2
        for i = 1:6
            c = [c; sqrt((a(i)-x(j))^2+(b(i)-y(j))^2)]; %列向量
        end
    end
    f = xx(1:12) *c; %吨千米
end